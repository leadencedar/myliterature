import type { WritingNorm } from '@/domain/schema';

/**
 * AI 精简写作规范的提示词（文案逐字取设计 1.5）。
 *
 * 作者手里的规范常是别处整理好的长文，真正有约束力的只有几节，来源表与核对说明
 * 却会在之后每次生成、摘要、提取时反复付费并稀释注意力。精简只是把它压成条目：
 * 明确禁止新增规则、禁止把「推测」「留白」改成确定说法 —— 规范的价值就在这些限定里。
 * 结果仍要经作者预览、另存为新规范，原文不被覆盖。
 */
export const NORM_CONDENSE_SYSTEM = [
  '你是一位小说编辑，负责把作者整理的写作规范压缩成可以直接放进提示词的约束条目。',
  '',
  '【任务】',
  '阅读作者给出的规范原文，只保留会约束创作与资料整理的内容，改写成简洁的条目。',
  '',
  '要求：',
  '- 保留：时间截面与冻结信息、与原作的版本差异、本作的改动及其后续影响、明确的边界与禁止事项、命名与合并规则、信息分层（谁知道什么）。',
  '- 删除：来源链接、参考网址、来源表与「能核对的内容」这类核对说明、重复表述、背景概述里不构成约束的叙述。',
  '- 不得新增原文没有的规则或事实，不得把原文的限定词（如「原作未明确」「推测」「留白」）改成确定说法。',
  '- 按原文的小节分组，每组一个以「## 」开头的小标题，组内每条以「- 」开头，一条一句。',
  '- 直接输出条目，不要任何开场白或解释。',
].join('\n');

/** 用户提示只放标题与原文：精简对象就是库里这一份，去首尾空白与注入时的渲染口径一致 */
export function buildCondenseUserPrompt(norm: Pick<WritingNorm, 'title' | 'content'>): string {
  return `【规范标题】\n${norm.title}\n\n【规范原文】\n${norm.content.trim()}`;
}
